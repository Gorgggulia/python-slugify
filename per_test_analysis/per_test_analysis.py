"""Per-test mutation analysis for mutmut: which tests kill which mutants.
Run from <project>/mutants (the directory generated by `mutmut run`)."""
import glob, json, os, sys, time
sys.path.insert(0, os.getcwd())
import pytest, slugify
assert os.getcwd() in os.path.abspath(slugify.__file__), slugify.__file__

class Rec:
    def __init__(self): self.failed=set(); self.all=set()
    def pytest_runtest_logreport(self, report):
        if report.when == 'call' or (report.when=='setup' and report.failed):
            self.all.add(report.nodeid)
            if report.failed: self.failed.add(report.nodeid)

def run():
    r = Rec()
    pytest.main(['-q','-p','no:cacheprovider','--tb=no','--no-header','-W','ignore::pytest.PytestUnraisableExceptionWarning','tests'], plugins=[r])
    return r

mutants = {}
for meta in glob.glob('slugify/*.py.meta'):
    d = json.load(open(meta))
    mutants.update(d['exit_code_by_key'])
names = sorted(mutants)
os.environ['MUTANT_UNDER_TEST'] = ''
base = run()
print('baseline failed:', base.failed, 'tests:', len(base.all), flush=True)
out = {'tests': sorted(base.all), 'baseline_failed': sorted(base.failed), 'mutants': {}}
PJ = '../../artifacts/per_test.json'
if os.path.exists(PJ):
    prev = json.load(open(PJ))
    if prev.get('tests') == out['tests']: out['mutants'] = prev['mutants']
print('resuming with', len(out['mutants']), 'done', flush=True)
t0 = time.time()
for i, n in enumerate(names):
    if n in out['mutants']: continue
    os.environ['MUTANT_UNDER_TEST'] = n
    r = run()
    out['mutants'][n] = {'mutmut_exit': mutants[n], 'killed_by': sorted(r.failed)}
    if i % 50 == 0:
        print(i, len(names), round(time.time()-t0), 's', flush=True)
        json.dump(out, open('../../artifacts/per_test.json', 'w'))
json.dump(out, open('../../artifacts/per_test.json', 'w'))
print('done', round(time.time()-t0), flush=True)
